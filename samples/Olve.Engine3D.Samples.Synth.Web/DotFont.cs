    private static readonly Dictionary<char, (uint Low, uint High)> Masks =
        ColumnsByChar.ToDictionary(pair => pair.Key, pair => ToMasks(pair.Value));

    /// <summary>The glyph's masks; a character the font lacks shows as '?'.</summary>
    public static (uint Low, uint High) Glyph(char c) =>
        Masks.TryGetValue(char.ToUpperInvariant(c), out var masks) ? masks : Masks['?'];

    /// <summary>The width of a line of text in dots, without the space after its last glyph.</summary>
    public static int Width(string text) => text.Length == 0 ? 0 : text.Length * Advance - 1;

    private static (uint Low, uint High) ToMasks(byte[] columns)
    {
        uint low = 0, high = 0;
        for (var x = 0; x < Columns; x++)
        {
            for (var y = 0; y < Rows; y++)
            {
                if ((columns[x] >> y & 1) == 0)
                {
                    continue;
                }

                if (y < 4)
                {
                    low |= 1u << (y * Columns + x);
                }
                else
                {
                    high |= 1u << ((y - 4) * Columns + x);
                }
            }
        }

        return (low, high);
    }
}
