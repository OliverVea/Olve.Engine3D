/// <summary>
/// A 5 by 7 dot-matrix font of capitals, digits and some punctuation, as the shape shader draws it: each glyph's dots
/// as two masks, rows 0-3 in the low and rows 4-6 in the high, five bits a row with the leftmost column lowest.
/// </summary>
public static class DotFont
{
    public const int Columns = 5;
    public const int Rows = 7;

    /// <summary>A glyph's width plus the space after it, in dots.</summary>
    public const int Advance = 6;

